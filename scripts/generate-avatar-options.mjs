/**
 * Regenerate src/lib/avatar-options.ts from the DiceBear HTTP API's
 * published JSON schemas (one per style). Run when adding styles or
 * bumping the DiceBear major version:
 *
 *   node scripts/generate-avatar-options.mjs
 *
 * For each style we keep:
 *  - enum "part" options (hair, eyes, mouth, …), noting whether a
 *    sibling `<name>Probability` exists (=> the part can be forced off)
 *  - color options (arrays of hex with a default palette)
 * Universal/layout props (seed, flip, scale, backgroundColor, …) are
 * excluded — the app handles seed + backgroundColor itself.
 */
import { writeFileSync } from "node:fs";

const STYLES = [
  "open-peeps", "adventurer", "avataaars", "big-ears", "big-smile",
  "bottts", "croodles", "fun-emoji", "lorelei", "micah", "miniavs",
  "notionists", "personas", "pixel-art", "thumbs",
];

const EXCLUDE = new Set([
  "seed", "flip", "rotate", "scale", "radius", "size", "backgroundColor",
  "backgroundType", "backgroundRotation", "translateX", "translateY",
  "clip", "randomizeIds", "base64",
]);

const COLOR_PATTERN = /\[a-fA-F0-9\]\{6\}/;

const out = {};
for (const style of STYLES) {
  const res = await fetch(`https://api.dicebear.com/9.x/${style}/schema.json`);
  if (!res.ok) throw new Error(`${style}: HTTP ${res.status}`);
  const schema = await res.json();
  const props = schema.properties ?? {};
  const options = {};

  for (const [name, def] of Object.entries(props)) {
    if (EXCLUDE.has(name) || name.endsWith("Probability")) continue;
    if (def.type !== "array" || !def.items) continue;

    if (Array.isArray(def.items.enum) && def.items.enum.length > 1) {
      options[name] = {
        kind: "enum",
        values: def.items.enum,
        hasProbability: `${name}Probability` in props,
      };
    } else if (
      typeof def.items.pattern === "string" &&
      COLOR_PATTERN.test(def.items.pattern) &&
      Array.isArray(def.default) &&
      def.default.length > 1 &&
      def.default.every((v) => /^[a-fA-F0-9]{6}$/.test(v))
    ) {
      options[name] = { kind: "color", values: def.default };
    }
  }
  out[style] = options;
  console.log(`${style}: ${Object.keys(options).join(", ") || "(none)"}`);
}

const file = `/**
 * GENERATED by scripts/generate-avatar-options.mjs — do not hand-edit.
 * Per-style customizable options extracted from the DiceBear 9.x
 * schemas (api.dicebear.com/9.x/<style>/schema.json).
 */
export type StyleOption =
  | { kind: "enum"; values: readonly string[]; hasProbability: boolean }
  | { kind: "color"; values: readonly string[] };

export const STYLE_OPTIONS: Record<string, Record<string, StyleOption>> =
${JSON.stringify(out, null, 2)};
`;

writeFileSync(new URL("../src/lib/avatar-options.ts", import.meta.url), file);
console.log("\nWrote src/lib/avatar-options.ts");
